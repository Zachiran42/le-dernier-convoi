#!/usr/bin/env node
'use strict';

// Post-process a Godot 4.7.2 single-thread Web export for GitHub's 25 MiB
// browser upload limit. The Wasm transport and game-pack URL are configured.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const crypto = require('node:crypto');
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const supportedWasmSha256 = 'fc74679e3b97f76878947fcd4fbe1268cbfa6188182a2e33bbc3f5dc9bfa57d0';

const [sourceArg, destinationArg] = process.argv.slice(2);
if (!sourceArg || !destinationArg) {
  console.error('Usage: node tools/pack-web.cjs <godot-web-export-directory> <publish-directory>');
  process.exit(2);
}
const source = fs.realpathSync(sourceArg);
const destination = path.resolve(destinationArg);
if (source.toLowerCase() === destination.toLowerCase()) throw new Error('Source and destination must differ; the raw export is retained.');
const htmlPath = path.join(source, 'index.html');
const javascriptPath = path.join(source, 'index.js');
const wasmPath = path.join(source, 'index.wasm');
let html = fs.readFileSync(htmlPath, 'utf8');
let javascript = fs.readFileSync(javascriptPath, 'utf8');
const originalLoad = 'loadPromise = preloader.loadPromise(`${loadPath}.wasm`, size, true);';
if (javascript.split(originalLoad).length !== 2) throw new Error('Unsupported Godot export: expected exactly one official Engine.load Wasm transport line.');
if (!html.includes('<script src="index.js"></script>')) throw new Error('Unsupported Godot HTML: index.js script tag not found.');
if (/const GODOT_THREADS_ENABLED\s*=\s*true/.test(html)) throw new Error('GitHub Pages package requires a single-thread export.');
const wasm = fs.readFileSync(wasmPath);
if (wasm.subarray(0, 4).toString('hex') !== '0061736d') throw new Error('Invalid WebAssembly header.');
if (sha256(wasm) !== supportedWasmSha256) throw new Error('Unsupported engine: this post-processor is verified for official Godot 4.7.2 single-thread release Wasm only.');
const gzip = zlib.gzipSync(wasm, { level: 9 });
if (!zlib.gunzipSync(gzip).equals(wasm)) throw new Error('Gzip round-trip failed.');
const uploadLimit = 25 * 1024 * 1024;
if (gzip.length >= uploadLimit) throw new Error('Compressed WebAssembly still exceeds GitHub browser upload limit.');

const loader = `/* Godot 4.7.2 Wasm gzip transport. Generated by tools/pack-web.cjs. */
(function () {
  'use strict';
  globalThis.ConvoiWasmLoader = Object.freeze({
    load: async function (url) {
      if (typeof DecompressionStream !== 'function') {
        throw new Error('Ce navigateur ne peut pas décompresser le jeu. Utilisez une version récente de Chrome, Firefox, Edge ou Safari.');
      }
      const response = await fetch(url, { credentials: 'same-origin' });
      if (!response.ok || !response.body) throw new Error('Chargement du moteur impossible : HTTP ' + response.status);
      // Return the same Response interface consumed by the official Engine.init.
      // No global fetch override, Blob URL or service worker is needed.
      return new Response(response.body.pipeThrough(new DecompressionStream('gzip')), {
        headers: { 'Content-Type': 'application/wasm' }
      });
    }
  });
}());
`;
javascript = '/* Modified for Le Dernier Convoi: Godot 4.7.2 official Engine.load transport uses a gzip Response from convoi-wasm-loader.js. The remaining generated engine code is retained. Godot MIT and third-party notices are distributed with the project. */\n' + javascript.replace(originalLoad, 'loadPromise = globalThis.ConvoiWasmLoader.load(`${loadPath}.wasm.gz`, size);');
html = html.replace('<script src="index.js"></script>', '<script src="convoi-wasm-loader.js"></script>\n\t\t<script src="index.js"></script>');
// Pin the game pack by content so a browser cannot reuse a previous campaign build.
// mainPack is a public Godot Engine configuration option; the engine is unchanged.
const pck = fs.readFileSync(path.join(source, 'index.pck'));
const mainPack = 'index.' + sha256(pck).slice(0, 12) + '.pck';
const configMatch = html.match(/const GODOT_CONFIG = (\{[^\n]+\});/);
if (!configMatch) throw new Error('Godot export configuration not found.');
const gameConfig = JSON.parse(configMatch[1]);
gameConfig.mainPack = mainPack;
gameConfig.fileSizes[mainPack] = pck.length;
html = html.replace(configMatch[0], 'const GODOT_CONFIG = ' + JSON.stringify(gameConfig) + ';');
fs.mkdirSync(destination, { recursive: true });
for (const item of fs.readdirSync(source, { withFileTypes: true })) {
  if (!item.isFile() || item.name === 'index.wasm' || item.name === 'index.html' || item.name === 'index.js') continue;
  fs.copyFileSync(path.join(source, item.name), path.join(destination, item.name));
}
// Remove only a previous raw engine artifact in this explicit publish directory.
const obsoleteRawWasm = path.join(destination, 'index.wasm');
if (fs.existsSync(obsoleteRawWasm)) fs.unlinkSync(obsoleteRawWasm);
fs.writeFileSync(path.join(destination, mainPack), pck);
fs.writeFileSync(path.join(destination, 'index.html'), html);
fs.writeFileSync(path.join(destination, 'index.js'), javascript);
fs.writeFileSync(path.join(destination, 'convoi-wasm-loader.js'), loader);
fs.writeFileSync(path.join(destination, 'index.wasm.gz'), gzip);
const files = fs.readdirSync(destination, { withFileTypes: true }).filter((item) => item.isFile() && item.name !== 'convoi-web-pack.json').map((item) => ({ name: item.name, bytes: fs.statSync(path.join(destination, item.name)).size }));
if (files.some((file) => file.bytes >= uploadLimit)) throw new Error('A publish file exceeds the GitHub browser upload limit.');
const report = {
  checkedAt: new Date().toISOString(), engine: 'Godot 4.7.2-stable official single-thread release',
  transport: 'gzip + DecompressionStream -> Response -> official Engine.init/instantiateWasm',
  originalWasm: { bytes: wasm.length, sha256: sha256(wasm) },
  gzipWasm: { bytes: gzip.length, sha256: sha256(gzip) },
  allFilesBelow25MiB: true, files,
};
fs.writeFileSync(path.join(destination, 'convoi-web-pack.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
